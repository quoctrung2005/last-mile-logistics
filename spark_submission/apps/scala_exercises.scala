import org.apache.spark.sql.functions._
import spark.implicits._
def section(s: String) = println("\n=== " + s + " ===")
section("Bai 5")
val numbers = sc.parallelize(List(12,15,20,25,30,35,40),2)
println(s"sum=${numbers.sum()}, min=${numbers.min()}, max=${numbers.max()}, mean=${numbers.mean()}, count=${numbers.count()}")
assert(numbers.sum() == 177 && numbers.count() == 7)
section("Bai 6")
val data6 = List("Python Spark Hadoop","Spark Scala Python","Hadoop Java Spark")
val unique = sc.parallelize(data6).flatMap(_.split("\\s+")).map(_.toLowerCase).distinct().sortBy(identity)
unique.collect().foreach(println)
section("Bai 7")
val data7 = List("Data Science with Spark","Spark supports Big Data","Big Data processing","Spark is powerful")
sc.parallelize(data7).flatMap(_.split("\\s+")).map(w => (w.toLowerCase,1)).reduceByKey(_+_).sortByKey().collect().foreach(println)
section("Bai 8")
val students = spark.read.option("header",true).schema("name STRING, age INT, major STRING, score DOUBLE").csv("/data/students.csv")
students.show(false)
students.filter($"major" === "Data").show(false)
students.filter($"score" >= 8.5).show(false)
students.select("name","major","score").show(false)
section("Bai 17")
val scores = sc.parallelize(List(6,7,8,9,10,5,8,7,9,6,10,8,7,9,5),2)
val high = scores.filter(_ >= 8).count()
println(s"sum=${scores.sum()}, mean=${scores.mean()}, max=${scores.max()}, min=${scores.min()}, >=8=$high, <5=${scores.filter(_ < 5).count()}, rate=${high*100.0/scores.count()}%")
assert(scores.sum() == 114 && high == 8)
